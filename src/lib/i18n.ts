const dictionaries: Record<Lang, Record<MessageKey, string>> = { fr, en }

export function translate(lang: Lang, key: MessageKey, params?: Record<string, string | number>): string {
  let text: string = dictionaries[lang][key]
  if (params) for (const [k, v] of Object.entries(params)) text = text.replaceAll(`{${k}}`, String(v))
  return text
}

export const detectLang = (): Lang =>
  (typeof navigator !== 'undefined' ? navigator.language : 'en').toLowerCase().startsWith('fr') ? 'fr' : 'en'
